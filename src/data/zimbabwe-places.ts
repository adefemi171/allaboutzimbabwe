export function getPlaceByCampusSlug(campusSlug: string): ZimbabwePlace | undefined {
  return ZIMBABWE_PLACES.find((p) => p.has3DCampus && p.campusSlug === campusSlug);
}

export function getPlacesForProvince(provinceSlug: string): ZimbabwePlace[] {
  return ZIMBABWE_PLACES.filter((p) => p.provinceSlug === provinceSlug);
}

/** A place's own 3D world if it has one, otherwise its province's city map. */
export function placeHref(place: ZimbabwePlace): string {
  return place.has3DCampus && place.campusSlug
    ? `/explore/${place.campusSlug}`
    : cityMapHref(place.provinceSlug);
}
